# Builds comparison.md from */results.csv and */timings.csv (run the four run.jl first).
#   julia benchmarks/twiss/compare.jl
using Printf
const HERE = @__DIR__
codes = ["optim", "bell", "cosy", "madx"]
rd(c, f) = (p = joinpath(HERE, c, f); isfile(p) ? Dict(split(l, ",")[1] => split(l, ",")[2] for l in readlines(p)[2:end]) : Dict())
R = Dict(c => rd(c, "results.csv") for c in codes)
num(x) = parse(Float64, x)
Q = [("C_m", "C_m"), ("Qx", "Qx"), ("Qy", "Qy"), ("Qx_frac", "Qx_frac"), ("Qy_frac", "Qy_frac"), ("xi_x", "xi_x"), ("xi_y", "xi_y"),
     ("xi_x_ptc_exact", ""), ("xi_y_ptc_exact", ""), ("alpha_c", "alpha_c"), ("eta_slip", "eta_slip"), ("eta_slip_ptc", ""),
     ("betx0_m", ""), ("bety0_m", ""), ("alfx0", ""), ("alfy0", ""), ("Dx0_m", ""), ("Dpx0", ""), ("Dx_end_m", ""),
     ("max_betx_m", ""), ("max_bety_m", ""), ("max_Dx_m", ""), ("I1", ""), ("I2", ""), ("I3", ""), ("I4", ""), ("I5", "")]
open(joinpath(HERE, "comparison.md"), "w") do io
    println(io, "# magnetic_2 — cross-code values (generated by compare.jl from actual runs)\n")
    println(io, "Units: m; D per delta_p = dp/p; xi = dQ/d(dp/p). Bell is the column the others are compared to (rel. diff in brackets).\n")
    println(io, "| quantity | ", join(codes, " | "), " |\n|---|", repeat("---|", length(codes)))
    for (q, _) in Q
        vals = [get(R[c], q, nothing) for c in codes]
        all(isnothing, vals) && continue
        q2 = q in ("Qx_frac", "Qy_frac") ? q : q
        b = get(R["bell"], q, nothing)
        if b === nothing && q in ("Qx_frac", "Qy_frac"); b = string(mod(num(R["bell"][q[1:2]]), 1)); end
        cells = map(vals) do v
            v === nothing && return "—"
            s = @sprintf("%.9g", num(v))
            (b !== nothing && num(b) != 0 && v !== b) ? s * @sprintf(" (%.1e)", num(v) / num(b) - 1) : s
        end
        println(io, "| ", q, " | ", join(cells, " | "), " |")
    end
    println(io, "\nManual reference (NOT from a run; OptiM GUI View|Integrals, entered by the user 2026-10-31): see optim/gui_reference_manual.txt")
    println(io, "\n## Timings (wall clock, s) — from */timings.csv\n")
    for c in codes
        p = joinpath(HERE, c, "timings.csv"); isfile(p) || continue
        println(io, "**", c, "**\n\n| stage | s |\n|---|---|")
        for l in readlines(p)[2:end]; a = split(l, ","); println(io, "| ", a[1], " | ", a[2], " |"); end
        println(io)
    end
end
print(read(joinpath(HERE, "comparison.md"), String))
