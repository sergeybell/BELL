const D8_B = D8_A[13, 1:12]
const D8_E3 = let e = [D8_B; 0.0]
    e[1] -= 0.244094488188976377952755905512; e[9] -= 0.733846688281611857341361741547
    e[12] -= 0.220588235294117647058823529412e-1; e
